#!/usr/bin/env python3
"""Build a conservative Shadowrocket module from approved rules only."""
from __future__ import annotations
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
APPROVED = ROOT / "sources/approved.rules"
BLOCKED = ROOT / "sources/blocked.rules"
MODULE = ROOT / "modules/phase2-group-test.module"
REPORT = ROOT / "reports/build.json"
DOMAIN_RE = re.compile(r"^(?=.{1,253}$)[a-z0-9](?:[a-z0-9-]*[a-z0-9])?(?:\\.[a-z0-9](?:[a-z0-9-]*[a-z0-9])?)+$")
DENY_SUFFIX = {"google.com", "googleapis.com", "gstatic.com", "cloudflare.com", "apple.com"}
NODE_A, NODE_B = "Tencent-US-Direct", "Tencent-US"

def parse(path: Path, allowed_policies: set[str]) -> list[tuple[str, str, str]]:
    result = []
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        fields = [part.strip() for part in line.split(",")]
        if len(fields) != 3:
            raise ValueError(f"{path.name}:{number}: expected TYPE,domain,POLICY")
        kind, domain, policy = fields
        domain = domain.lower().rstrip(".")
        if kind not in {"DOMAIN", "DOMAIN-SUFFIX"} or policy not in allowed_policies:
            raise ValueError(f"{path.name}:{number}: unsupported rule")
        if not DOMAIN_RE.fullmatch(domain):
            raise ValueError(f"{path.name}:{number}: invalid domain {domain}")
        if kind == "DOMAIN-SUFFIX" and domain in DENY_SUFFIX:
            raise ValueError(f"{path.name}:{number}: unsafe broad suffix {domain}")
        result.append((kind, domain, policy))
    return sorted(set(result), key=lambda x: (x[1], x[0], x[2]))

def overlaps(kind: str, domain: str, other_kind: str, other: str) -> bool:
    if kind == "DOMAIN" and other_kind == "DOMAIN":
        return domain == other
    if kind == "DOMAIN" and other_kind == "DOMAIN-SUFFIX":
        return domain == other or domain.endswith("." + other)
    if kind == "DOMAIN-SUFFIX" and other_kind == "DOMAIN":
        return other == domain or other.endswith("." + domain)
    return domain == other or domain.endswith("." + other) or other.endswith("." + domain)

def build() -> tuple[str, dict]:
    rules = parse(APPROVED, {"AI-PROXY"})
    blocked = parse(BLOCKED, {"REJECT"})
    if not rules:
        raise ValueError("Empty approved ruleset: refusing to publish")
    conflicts = [
        {"approved": ",".join(a), "blocked": ",".join(b)}
        for a in rules for b in blocked if overlaps(a[0], a[1], b[0], b[1])
    ]
    # Exceptions are ordered first, ensuring the explicit block wins.
    lines = [
        "#!name=xke AI Routing - Test",
        "#!desc=Curated AI routing; generated by RocketGo_Rules. Keep original main config.",
        "",
        "[Proxy Group]",
        f"AI-PROXY = select,{NODE_A},{NODE_B}",
        "",
        "[Rule]",
        "# Preserve explicitly blocked subdomains before broad AI suffix rules",
        *(",".join(rule) for rule in blocked),
        "",
        "# OpenAI and Google AI: manually approved domains only",
        *(",".join(rule) for rule in rules),
        "",
    ]
    report = {
        "approved_count": len(rules),
        "blocked_count": len(blocked),
        "conflicts_handled_by_precedence": conflicts,
        "notes": [
            "No unreviewed upstream rules are auto-published.",
            "Compare blocked.rules against your current main configuration periodically.",
            "This module does not manage node credentials or the primary configuration.",
        ],
    }
    return "\n".join(lines), report

def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if generated files differ")
    args = parser.parse_args()
    content, report = build()
    expected = {MODULE: content, REPORT: json.dumps(report, indent=2, ensure_ascii=False) + "\n"}
    if args.check:
        stale = [str(p.relative_to(ROOT)) for p, data in expected.items() if not p.exists() or p.read_text(encoding="utf-8") != data]
        if stale:
            raise SystemExit("Generated files out of date: " + ", ".join(stale))
        print("Generated files match.")
    else:
        for path, data in expected.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(data, encoding="utf-8")
        print(f"Generated {len(report['conflicts_handled_by_precedence'])} explicit rule overlap(s).")

if __name__ == "__main__":
    main()
